function levels(label, strong, proficient, developing, beginning, feedback) {
  return { label, exemplary: strong, proficient, developing, beginning, feedback };
}
export function chineseIndependentTask(task) {
  const kind = task.family || (task.kind === 'source-proportion' ? 'calculation' : 'source-analysis');
  let sources, directions, answer, reasoning, rubric, feedback;
  if (kind === 'calculation') {
    sources = ['新的虚构情境：社团收到48份表格，其中36份回答了是否参加活动，15份选择参加；另外12份没有回答这一题。'];
    directions =
      '计算有效回答中选择参加的比例（百分比保留两位小数），解释分母的选择，并说明能否确定全部48人的参加比例。';
    answer =
      '分母为有效回答的36人，因此15/36≈41.67%；精确检验为(15/36)×36=15。48是全部交表人数，用15/48回答的是另一问题。未回答的12人的意愿未知，不能把他们算成不参加，也不能据此确定全部48人的参加比例。';
    reasoning = [
      '区分全部交表者、有效回答者与选择参加者。',
      '以所求群体的36人为分母，计算15/36并标明舍入。',
      '把12人的未知意愿与已知“不参加”区分。',
    ];
    rubric = [
      levels(
        '选择相应分母',
        '用36作为分母，说明48会改变所求群体。',
        '用36并说明它是有效回答人数，但未比较48。',
        '分母为36，但没有解释。',
        '把48当成有效回答人数。',
        '先圈出题目所求的群体。',
      ),
      levels(
        '计算与检验',
        '15/36≈41.67%，并用精确分数完成反向检验。',
        '分数和百分比正确、近似号恰当，但缺少检验。',
        '仅给出41.67%。',
        '换算错误，或声称舍入后仍完全相等。',
        '保留精确分数，舍入仅用于最终显示。',
      ),
      levels(
        '解释缺失信息',
        '明确12人意愿未知，解释为何不能确定48人的比例。',
        '指出12人未知，未解释对总体计算的影响。',
        '只笼统地说有误差。',
        '把未回答直接算成不参加。',
        '区分未观察与已观察的否定回答。',
      ),
    ];
    feedback = '先核对分母，再检查舍入，最后确认没有把缺失回答改写成已知意愿。';
  } else if (kind === 'experiment') {
    sources = [
      '新的虚构情境：纸张甲为10×10厘米，纸张乙为20×20厘米。两种纸都浸水10秒，测量浸水前后的质量增加。每种纸只有一次测量，尚未给出测量值。',
    ];
    directions = '判断这能否单独比较纸张类型的吸水效果，提出可执行的改进，并说明目前能否判断哪种纸更好。';
    answer =
      '纸张类型与面积同时改变；较大的吸水量可能来自较大的面积。应将两种纸裁为相同面积，统一浸水10秒及沥水、称量方法，随机决定测量顺序，对每种纸使用独立样本重复测量，记录质量增加并比较变动。还没有新结果，不能断言哪种纸更好。';
    reasoning = [
      '10×10与20×20面积不同，面积与纸型混杂。',
      '保持面积和测量流程一致，独立重复并记录数据。',
      '新方案是建议，不能替代新的测量结果。',
    ];
    rubric = [
      levels(
        '定位混杂',
        '明确面积与纸型同时改变，并解释吸水量可能随面积变化。',
        '指出面积与纸型不同，但未解释竞争原因。',
        '只说“不公平”。',
        '直接把差异归因于纸型。',
        '分别计算或比较两组面积。',
      ),
      levels(
        '写出可核对的操作',
        '同面积、同浸水和称量流程，随机顺序、独立样本重复，并说明记录质量增加。',
        '保持面积与流程一致并测量，但漏掉顺序或重复之一。',
        '只建议用一样大小的纸。',
        '增加次数却保留原来不同面积。',
        '写明改变什么、保持什么及怎样测量。',
      ),
      levels(
        '区分方案与结果',
        '明确没有结果，需比较新数据及变动后才能判断。',
        '指出还需数据，但未说明比较什么。',
        '笼统说需要更多研究。',
        '声称修改设计已经证明某种纸更好。',
        '把已知观察、拟议操作和未知结果分列。',
      ),
    ];
    feedback = '修复面积差异后，再核对测量方法与独立重复；最后删去没有数据支持的优劣结论。';
  } else {
    sources = [
      '新的虚构情境：记录甲称某电台首次播音于1941年；记录乙称同一电台首次播音于1942年。记录丙是一份1940年的建筑许可，未记载任何播音日期。',
    ];
    directions = '判断哪些记录存在冲突，解释记录丙能否解决争议，并提出一项可以寻找的新证据。';
    answer =
      '甲与乙都声称记录首次播音，却给出1941和1942两个不同年份，因此存在冲突。建筑许可描述的是另一事件，不能确定首次播音日期。可寻找独立、可核对日期的首次节目播出日志或同期节目公告，并核对它是否确实指首次播音；这些资料尚未获得，所以目前不能选定正确年份。';
    reasoning = [
      '先给每个日期标注所指事件。',
      '同一事件、不同年份构成冲突；不同事件的早期日期不直接解决它。',
      '说明需要哪种记录及如何比较，同时保留未解决状态。',
    ];
    rubric = [
      levels(
        '绑定事件与日期',
        '甲1941、乙1942均为首次播音，丙1940为建筑许可。',
        '正确区分事件，但漏标一个来源。',
        '抄出日期而未标事件。',
        '把建筑许可当成首次播音。',
        '给每个日期写出事件与来源。',
      ),
      levels(
        '解释记录关系',
        '解释甲乙冲突，且丙不能解决首次播音争议。',
        '判断正确，但只解释冲突或丙的限制之一。',
        '只说日期不同。',
        '据较早许可直接选定播音年份。',
        '检查各条记录是否回答同一个问题。',
      ),
      levels(
        '提出取证步骤并保留未知',
        '提出日志或同期公告，说明核对事件与日期，并保留未解决结论。',
        '提出相关记录并保留未知，但未说明怎样核对。',
        '只说需要更多资料。',
        '虚构已获得的新记录或直接判定一方正确。',
        '写出要找的记录、要核对的内容，以及它可能改变什么结论。',
      ),
    ];
    feedback = '先检查事件是否相同，再判断日期关系；不能用另一事件的日期替代所求日期。';
  }
  return {
    sources,
    directions,
    question: `独立完成：${sources.join(' ')} ${directions}`,
    answer,
    reasoning,
    rubric,
    feedback,
  };
}
